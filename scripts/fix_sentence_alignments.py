# -*- coding: utf-8 -*-
import json

def fix_unit(unit_num, s_id, p_idx, new_zh):
    path = f'单词故事本/Unit{unit_num:02d}.json'
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    for st in data['stories']:
        if st['id'] == s_id:
            st['ps'][p_idx]['zh'] = new_zh
            break
    with open(path, 'w', encoding='utf-8', newline='') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f'Fixed Unit {unit_num:02d} {s_id} p{p_idx}')

